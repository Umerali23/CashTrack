import { useState, useEffect, useCallback, useMemo } from 'react';
import { supabase } from '../lib/supabase';
import { convertAmount } from '../lib/currency';
import { useAuth } from '../context/AuthContext';

export const useCashTrack = () => {
  const { user } = useAuth();
  const [data, setData] = useState({
    clients: [], profiles: [], tasks: [], invoices: [], transactions: [], payouts: []
  });
  const [loading, setLoading] = useState(true);
  const [displayCurrency, setDisplayCurrency] = useState('PKR');
  const [theme, setTheme] = useState(() => localStorage.getItem('cashtrack_theme') || 'dark');

  // Fetch all data from Supabase
  const fetchData = useCallback(async () => {
    if (!user) {
      setLoading(false);
      return;
    }

    setLoading(true);
    try {
      const [
        { data: clients },
        { data: profiles },
        { data: tasks },
        { data: invoices },
        { data: transactions },
        { data: payouts }
      ] = await Promise.all([
        supabase.from('clients').select('*').order('created_at', { ascending: false }),
        supabase.from('profiles').select('*').order('created_at', { ascending: false }),
        supabase.from('tasks').select('*').order('created_at', { ascending: false }),
        supabase.from('invoices').select('*').order('created_at', { ascending: false }),
        supabase.from('transactions').select('*').order('created_at', { ascending: false }),
        supabase.from('payouts').select('*').order('created_at', { ascending: false })
      ]);

      // Format data: convert snake_case to camelCase
      const formatted = {
        clients: clients?.map(c => ({ ...c, avatarColor: c.avatar_color })) || [],
        profiles: profiles?.map(p => ({ ...p, avatarColor: p.avatar_color })) || [],
        tasks: tasks?.map(t => ({
          ...t,
          clientId: t.client_id,
          assigneeId: t.assignee_id,
          dueDate: t.due_date,
          completedAt: t.completed_at,
          createdAt: t.created_at
        })) || [],
        invoices: invoices?.map(i => ({
          ...i,
          clientId: i.client_id,
          createdBy: i.created_by,
          issueDate: i.issue_date,
          dueDate: i.due_date,
          linkedTaskIds: i.linked_task_ids || []
        })) || [],
        transactions: transactions?.map(t => ({
          ...t,
          clientId: t.client_id,
          assigneeId: t.assignee_id,
          isAutoGenerated: t.is_auto_generated,
          linkedInvoiceId: t.linked_invoice_id,
          createdAt: t.created_at
        })) || [],
        payouts: payouts?.map(p => ({
          ...p,
          memberId: p.member_id,
          taskId: p.task_id,
          invoiceId: p.invoice_id,
          invoiceNumber: p.invoice_number,
          createdAt: p.created_at
        })) || []
      };

      setData(formatted);
    } catch (error) {
      console.error('Error fetching data:', error);
    } finally {
      setLoading(false);
    }
  }, [user]);

  useEffect(() => {
    fetchData();
  }, [fetchData]);

  useEffect(() => {
    document.documentElement.className = theme;
    localStorage.setItem('cashtrack_theme', theme);
  }, [theme]);

  // --- CRUD OPERATIONS ---

  // CLIENTS
  const addClient = async (client) => {
    const newClient = {
      id: crypto.randomUUID(),
      name: client.name,
      company: client.company,
      email: client.email,
      avatar_color: client.avatarColor,
      created_at: new Date().toISOString()
    };

    const { error } = await supabase.from('clients').insert([newClient]);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      clients: [{ ...newClient, avatarColor: newClient.avatar_color }, ...prev.clients]
    }));
  };

  const updateClient = async (id, patch) => {
    const { error } = await supabase
      .from('clients')
      .update({
        name: patch.name,
        company: patch.company,
        email: patch.email,
        avatar_color: patch.avatarColor
      })
      .eq('id', id);

    if (error) throw error;

    setData(prev => ({
      ...prev,
      clients: prev.clients.map(c => c.id === id ? { ...c, ...patch } : c)
    }));
  };

  const deleteClient = async (id) => {
    const { error } = await supabase.from('clients').delete().eq('id', id);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      clients: prev.clients.filter(c => c.id !== id)
    }));
  };

  // TEAM MEMBERS
  const addTeamMember = async (member) => {
    const result = await supabase.auth.signUp({
      email: member.email,
      password: member.password,
      options: {
        data: {
          name: member.name,
          role: member.role,
          avatar_color: member.avatarColor,
          password: member.password
        }
      }
    });

    if (result.error) throw result.error;

    // The trigger will auto-create the profile
    await fetchData(); // Refresh data

    return { success: true, creds: { email: member.email, password: member.password } };
  };

  const updateTeamMember = async (id, patch) => {
    const { error } = await supabase
      .from('profiles')
      .update({
        name: patch.name,
        role: patch.role,
        email: patch.email,
        avatar_color: patch.avatarColor
      })
      .eq('id', id);

    if (error) throw error;

    setData(prev => ({
      ...prev,
      profiles: prev.profiles.map(m => m.id === id ? { ...m, ...patch } : m)
    }));
  };

  const deleteTeamMember = async (id) => {
    // Note: This only deletes profile, not auth user (requires admin API)
    const { error } = await supabase.from('profiles').delete().eq('id', id);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      profiles: prev.profiles.filter(m => m.id !== id)
    }));
  };

  // TASKS
  const addTask = async (task) => {
    const newTask = {
      id: crypto.randomUUID(),
      title: task.title,
      description: task.description,
      status: task.status || 'pending',
      priority: task.priority || 'medium',
      tags: Array.isArray(task.tags) ? task.tags.join(',') : task.tags,
      due_date: task.dueDate,
      compensation: parseFloat(task.compensation) || 0,
      currency: task.currency || 'USD',
      client_id: task.clientId,
      assignee_id: task.assigneeId,
      created_at: new Date().toISOString()
    };

    const { error } = await supabase.from('tasks').insert([newTask]);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      tasks: [{
        ...newTask,
        clientId: newTask.client_id,
        assigneeId: newTask.assignee_id,
        dueDate: newTask.due_date,
        createdAt: newTask.created_at
      }, ...prev.tasks]
    }));
  };

  const updateTask = async (id, patch) => {
    const updateData = {
      title: patch.title,
      description: patch.description,
      status: patch.status,
      priority: patch.priority,
      tags: Array.isArray(patch.tags) ? patch.tags.join(',') : patch.tags,
      due_date: patch.dueDate,
      compensation: patch.compensation,
      currency: patch.currency,
      client_id: patch.clientId,
      assignee_id: patch.assigneeId,
      completed_at: patch.status === 'completed' ? new Date().toISOString() : null
    };

    const { error } = await supabase.from('tasks').update(updateData).eq('id', id);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      tasks: prev.tasks.map(t => t.id === id ? { ...t, ...patch } : t)
    }));
  };

  const deleteTask = async (id) => {
    const { error } = await supabase.from('tasks').delete().eq('id', id);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      tasks: prev.tasks.filter(t => t.id !== id)
    }));
  };

  // INVOICES
  const addInvoice = async (invoice) => {
    const newInvoice = {
      id: crypto.randomUUID(),
      invoice_number: invoice.invoiceNumber,
      client_id: invoice.clientId,
      created_by: invoice.createdBy,
      status: invoice.status || 'draft',
      total: parseFloat(invoice.total) || 0,
      currency: invoice.currency || 'USD',
      items: invoice.items,
      issue_date: invoice.issueDate,
      due_date: invoice.dueDate,
      linked_task_ids: invoice.linkedTaskIds,
      created_at: new Date().toISOString()
    };

    const { error } = await supabase.from('invoices').insert([newInvoice]);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      invoices: [{
        ...newInvoice,
        clientId: newInvoice.client_id,
        createdBy: newInvoice.created_by,
        issueDate: newInvoice.issue_date,
        dueDate: newInvoice.due_date
      }, ...prev.invoices]
    }));

    return newInvoice;
  };

  const updateInvoice = async (id, patch) => {
    const { error } = await supabase
      .from('invoices')
      .update({
        status: patch.status,
        total: patch.total,
        items: patch.items,
        due_date: patch.dueDate
      })
      .eq('id', id);

    if (error) throw error;

    setData(prev => ({
      ...prev,
      invoices: prev.invoices.map(i => i.id === id ? { ...i, ...patch } : i)
    }));
  };

  const deleteInvoice = async (id) => {
    const { error } = await supabase.from('invoices').delete().eq('id', id);
    if (error) throw error;

    setData(prev => ({
      ...prev,
      invoices: prev.invoices.filter(i => i.id !== id)
    }));
  };

  const markInvoiceAsPaid = async (invoiceId) => {
    // Get invoice details
    const { data: invoice } = await supabase
      .from('invoices')
      .select('*')
      .eq('id', invoiceId)
      .single();

    if (!invoice) throw new Error('Invoice not found');

    // Update invoice status
    await supabase.from('invoices').update({ status: 'paid' }).eq('id', invoiceId);

    // Create transaction
    const txId = crypto.randomUUID();
    await supabase.from('transactions').insert([{
      id: txId,
      type: 'income',
      amount: invoice.total,
      currency: invoice.currency,
      client_id: invoice.client_id,
      assignee_id: invoice.created_by,
      category: 'Client Payment',
      date: new Date().toISOString().split('T')[0],
      description: `Payment for Invoice ${invoice.invoice_number}`,
      status: 'paid',
      is_auto_generated: true,
      linked_invoice_id: invoiceId,
      created_at: new Date().toISOString()
    }]);

    // Create payouts for team members
    if (invoice.linked_task_ids && invoice.linked_task_ids.length > 0) {
      const { data: tasks } = await supabase
        .from('tasks')
        .select('id, assignee_id, compensation, currency, title')
        .in('id', invoice.linked_task_ids);

      if (tasks) {
        for (const task of tasks) {
          if (task.assignee_id) {
            const poId = crypto.randomUUID();
            await supabase.from('payouts').insert([{
              id: poId,
              member_id: task.assignee_id,
              amount: task.compensation,
              currency: task.currency,
              task_id: task.id,
              task_title: task.title,
              invoice_id: invoiceId,
              invoice_number: invoice.invoice_number,
              date: new Date().toISOString().split('T')[0],
              status: 'paid',
              created_at: new Date().toISOString()
            }]);
          }
        }
      }
    }

    // Refresh all data
    await fetchData();
  };

  const generateInvoiceFromTasks = async (taskIds, clientId) => {
    const { data: tasks } = await supabase
      .from('tasks')
      .select('*')
      .in('id', taskIds);

    if (!tasks || tasks.length === 0) return null;

    const total = tasks.reduce((sum, t) => sum + (parseFloat(t.compensation) || 0), 0);
    const items = tasks.map(t => ({
      description: t.title,
      amount: parseFloat(t.compensation) || 0,
      taskId: t.id
    }));

    const invoice = {
      invoiceNumber: `INV-${Date.now().toString().slice(-6)}`,
      clientId,
      createdBy: user?.id,
      status: 'draft',
      total,
      currency: 'USD',
      items,
      issueDate: new Date().toISOString().split('T')[0],
      dueDate: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString().split('T')[0],
      linkedTaskIds: taskIds
    };

    return await addInvoice(invoice);
  };

  // TRANSACTIONS
  const addManualIncome = async (transaction) => {
    const txId = crypto.randomUUID();
    await supabase.from('transactions').insert([{
      id: txId,
      type: 'income',
      amount: parseFloat(transaction.amount),
      currency: transaction.currency,
      client_id: transaction.clientId,
      assignee_id: transaction.assigneeId,
      category: transaction.category,
      date: transaction.date,
      description: transaction.description,
      status: 'paid',
      is_auto_generated: false,
      created_at: new Date().toISOString()
    }]);

    await fetchData();
  };

  const addExpense = async (expense) => {
    const txId = crypto.randomUUID();
    await supabase.from('transactions').insert([{
      id: txId,
      type: 'expense',
      amount: parseFloat(expense.amount),
      currency: expense.currency,
      category: expense.category,
      date: expense.date,
      description: expense.description,
      status: 'paid',
      is_auto_generated: false,
      created_at: new Date().toISOString()
    }]);

    await fetchData();
  };

  // --- DATA PROCESSING ---
  const toDisplay = useCallback((amount, originalCurrency) => 
    convertAmount(amount || 0, originalCurrency || 'USD', displayCurrency), 
    [displayCurrency]
  );

  const aggregates = useMemo(() => {
    const now = new Date();
    const thisMonthStart = new Date(now.getFullYear(), now.getMonth(), 1);
    let income = 0, expense = 0;

    (data.transactions || []).forEach((t) => {
      const d = new Date(t.date || t.createdAt || Date.now());
      const displayAmt = toDisplay(t.amount || 0, t.currency);
      if (d >= thisMonthStart) {
        if (t.type === 'income') income += displayAmt;
        else expense += displayAmt;
      }
    });

    return { income, expense, net: income - expense };
  }, [data.transactions, toDisplay]);

  const memberEarnings = useMemo(() => {
    if (!user) return { total: 0, completedTasks: 0, pendingTasks: 0, taskBreakdown: [], payouts: [] };

    const myTasks = (data.tasks || []).filter(t => t.assigneeId === user.id);
    const completedTasks = myTasks.filter(t => t.status === 'completed');
    const totalEarnings = completedTasks.reduce((sum, t) => 
      sum + toDisplay(parseFloat(t.compensation) || 0, t.currency), 0
    );

    const taskBreakdown = completedTasks.map(t => ({
      ...t,
      earnings: toDisplay(parseFloat(t.compensation) || 0, t.currency),
      client: (data.clients || []).find(c => c.id === t.clientId)
    }));

    const myPayouts = (data.payouts || []).filter(p => p.memberId === user.id);

    return {
      total: totalEarnings,
      completedTasks: completedTasks.length,
      pendingTasks: myTasks.filter(t => t.status !== 'completed').length,
      taskBreakdown,
      payouts: myPayouts
    };
  }, [data.tasks, data.clients, data.payouts, user, toDisplay]);

  return {
    data, setData, loading, displayCurrency, setDisplayCurrency, theme, setTheme,
    addClient, updateClient, deleteClient,
    addTeamMember, updateTeamMember, deleteTeamMember,
    addTask, updateTask, deleteTask,
    addInvoice, updateInvoice, deleteInvoice, markInvoiceAsPaid,
    generateInvoiceFromTasks, addManualIncome, addExpense,
    toDisplay, aggregates, memberEarnings
  };
};